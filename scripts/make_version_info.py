# -*- coding: utf-8 -*-
"""由 `app/version.py` 生成 PyInstaller 的 Windows 版本资源（VSVersionInfo）。

为什么需要：exe 以前只带图标，没有版本资源，右键「属性 → 详细信息」里
文件版本 / 产品版本是空的。用户手里只有一个 25MB 的包，唯一能确认「这是
哪一版」的入口就是打开应用看设置——多绕一步，而且装成旧包时也很难自证。
补上之后资源管理器里一看便知，同时也少一层「无版本信息的 exe」的警惕。

用法：
    python scripts/make_version_info.py                 # 版本取 app/version.py
    python scripts/make_version_info.py 2.0.1 -o build/version_info.txt

**唯一来源仍然是 `app/version.py`**：这里的命令行参数只是给验证用的，
CI 与 `FoodieTrail.spec` 都不传参，直接读 VERSION。

注意：生成的是 Python 字面量文本，PyInstaller 会按 `encoding` cookie 读取。
字符串与注释一律用 ASCII——万一某个读取路径按系统 locale 解码，中文会变成
乱码甚至解码失败，而版本资源完全没有必要冒这个险。
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

DEFAULT_OUT = ROOT / "build" / "version_info.txt"

# 打包进 exe 的固定元数据（不是版本号，改不改都不影响更新逻辑）
DESCRIPTION = "Foodie Trail - map of every place you have eaten"
PRODUCT = "Foodie Trail"
INTERNAL = "FoodieTrail"
ORIGINAL = "FoodieTrail.exe"
COMPANY = ""
COPYRIGHT = ""


def parse_version(text):
    """`2.0.1` → `(2, 0, 1, 0)`。Windows 的版本资源必须是四段。"""
    raw = (text or "").strip().lstrip("vV")
    parts = raw.split(".")
    if len(parts) < 2 or len(parts) > 4 or not all(p.isdigit() for p in parts):
        raise ValueError(f"版本号不合法：{text!r}（应为 2.0.1 这种形式）")
    nums = [int(p) for p in parts]
    while len(nums) < 4:
        nums.append(0)
    return tuple(nums)


def render(version):
    """返回可直接交给 PyInstaller `version=` 的文本。"""
    nums = parse_version(version)
    ver = (version or "").strip().lstrip("vV")
    quad = ", ".join(str(n) for n in nums)
    return f"""# -*- coding: utf-8 -*-
# Generated by scripts/make_version_info.py -- do not edit.
# The version lives in app/version.py; editing here changes nothing at runtime.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({quad}),
    prodvers=({quad}),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0),
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          "040904B0",
          [
            StringStruct("CompanyName", "{COMPANY}"),
            StringStruct("FileDescription", "{DESCRIPTION}"),
            StringStruct("FileVersion", "{ver}"),
            StringStruct("InternalName", "{INTERNAL}"),
            StringStruct("LegalCopyright", "{COPYRIGHT}"),
            StringStruct("OriginalFilename", "{ORIGINAL}"),
            StringStruct("ProductName", "{PRODUCT}"),
            StringStruct("ProductVersion", "{ver}"),
          ],
        )
      ],
    ),
    VarFileInfo([VarStruct("Translation", [1033, 1200])]),
  ],
)
"""


def write_version_file(version=None, out=None):
    """写文件并返回路径。`version` 为空时读 `app/version.py`。"""
    if not version:
        from app.version import VERSION
        version = VERSION
    target = Path(out) if out else DEFAULT_OUT
    target.parent.mkdir(parents=True, exist_ok=True)
    # 固定 UTF-8 + LF：CI 与本机生成同一个文件，方便比对
    target.write_text(render(version), encoding="utf-8", newline="\n")
    return str(target)


def main():
    ap = argparse.ArgumentParser(description="生成 Windows exe 的版本资源")
    ap.add_argument("version", nargs="?", default=None, help="默认取 app/version.py")
    ap.add_argument("-o", "--out", default=None, help=f"输出路径，默认 {DEFAULT_OUT}")
    args = ap.parse_args()
    try:
        path = write_version_file(args.version, args.out)
    except ValueError as e:
        print(f"[version-info] {e}")
        return 2
    print(f"[version-info] {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
